CREATE TYPE public.user_role AS ENUM ('admin', 'monitor', 'aluno');

CREATE TYPE public.student_category AS ENUM ('frequente', 'academico', 'visitante');

CREATE TYPE public.event_type AS ENUM ('tournament', 'graduation', 'seminar', 'other');

