-- 5. FUNCOES AUXILIARES
-- ---------------------------------------------------------------------------

-- Verifica se o usuario autenticado e administrador
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = auth.uid() AND role = 'admin'
  );
$$;

-- Verifica se o usuario autenticado e administrador ou monitor
CREATE OR REPLACE FUNCTION public.is_admin_or_monitor()
RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = auth.uid() AND role IN ('admin', 'monitor')
  );
$$;

-- Atualiza campo updated_at automaticamente (versao timezone UTC)
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = timezone('utc'::text, now());
  RETURN NEW;
END;
$$;

-- Atualiza campo updated_at automaticamente (versao simples)
CREATE OR REPLACE FUNCTION public.update_updated_at_column()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

-- Cria perfil automaticamente quando um novo usuario se registra
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  INSERT INTO public.profiles (
    id, full_name, email, role, category, gender, institution, enrollment_id,
    phone, emergency_contact, ufpe_bond, academic_level, sexual_orientation, gender_identity
  )
  VALUES (
    NEW.id,
    COALESCE(NEW.raw_user_meta_data->>'full_name', 'Novo Aluno'),
    NEW.email,
    COALESCE((NEW.raw_user_meta_data->>'role')::public.user_role, 'aluno'),
    COALESCE((NEW.raw_user_meta_data->>'category')::public.student_category, 'visitante'),
    NEW.raw_user_meta_data->>'gender',
    NEW.raw_user_meta_data->>'institution',
    NEW.raw_user_meta_data->>'enrollment_id',
    NEW.raw_user_meta_data->>'phone',
    NEW.raw_user_meta_data->>'emergency_contact',
    NEW.raw_user_meta_data->>'ufpe_bond',
    NEW.raw_user_meta_data->>'academic_level',
    NEW.raw_user_meta_data->>'sexual_orientation',
    NEW.raw_user_meta_data->>'gender_identity'
  );
  RETURN NEW;
END;
$$;

-- Sincroniza delecao de perfil com auth.users
CREATE OR REPLACE FUNCTION public.handle_deleted_profile()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  DELETE FROM auth.users WHERE id = OLD.id;
  RETURN OLD;
END;
$$;


-- ---------------------------------------------------------------------------
-- 6. TRIGGERS
-- ---------------------------------------------------------------------------

-- Criacao automatica de perfil ao registrar usuario
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- Sincronizacao de delecao de perfil
CREATE TRIGGER on_profile_deleted
  AFTER DELETE ON profiles
  FOR EACH ROW EXECUTE FUNCTION handle_deleted_profile();

-- Atualizacao automatica de updated_at
CREATE TRIGGER set_updated_at_profiles
  BEFORE UPDATE ON profiles
  FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

CREATE TRIGGER set_updated_at_workouts
  BEFORE UPDATE ON workouts
  FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

CREATE TRIGGER set_updated_at_graduations
  BEFORE UPDATE ON graduations
  FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

CREATE TRIGGER set_updated_at_events
  BEFORE UPDATE ON events
  FOR EACH ROW EXECUTE FUNCTION handle_updated_at();

CREATE TRIGGER set_updated_at_announcements
  BEFORE UPDATE ON announcements
  FOR EACH ROW EXECUTE FUNCTION handle_updated_at();


