-- Perfis de usuario (vinculados a auth.users do Supabase)
CREATE TABLE public.profiles (
  id uuid NOT NULL,
  full_name text NOT NULL,
  email text NOT NULL,
  role user_role NOT NULL DEFAULT 'aluno'::user_role,
  belt text DEFAULT 'Branca'::text,
  category student_category NOT NULL DEFAULT 'visitante'::student_category,
  institution text,
  enrollment_id text,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  gender text,
  phone text,
  emergency_contact text,
  ufpe_bond text,
  academic_level text,
  sexual_orientation text,
  gender_identity text,
  cpf text,

  CONSTRAINT profiles_pkey PRIMARY KEY (id),
  CONSTRAINT profiles_id_fkey FOREIGN KEY (id) REFERENCES auth.users(id) ON DELETE CASCADE,
  CONSTRAINT profiles_email_key UNIQUE (email),
  CONSTRAINT profiles_cpf_unique UNIQUE (cpf),
  CONSTRAINT profiles_full_name_not_empty CHECK (length(TRIM(BOTH FROM full_name)) > 0),
  CONSTRAINT profiles_email_format CHECK (email ~* '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'),
  CONSTRAINT profiles_cpf_format CHECK (cpf IS NULL OR cpf ~ '^\d{11}$')
);

-- Principios do Jiu-Jitsu (32 principios fundamentais)
CREATE TABLE public.principles (
  id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  number integer NOT NULL,
  title_pt text NOT NULL,
  title_en text NOT NULL,
  description text NOT NULL,
  category text,

  CONSTRAINT principles_pkey PRIMARY KEY (id),
  CONSTRAINT principles_number_key UNIQUE (number),
  CONSTRAINT principles_number_range CHECK (number >= 1 AND number <= 32),
  CONSTRAINT principles_title_pt_not_empty CHECK (length(TRIM(BOTH FROM title_pt)) > 0),
  CONSTRAINT principles_title_en_not_empty CHECK (length(TRIM(BOTH FROM title_en)) > 0)
);

-- Aulas registradas
CREATE TABLE public.workouts (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  date date NOT NULL,
  technique_name text NOT NULL,
  technique_what text NOT NULL,
  technique_how text NOT NULL,
  technique_why text NOT NULL,
  principle_id integer NOT NULL,
  registered_by uuid NOT NULL,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),

  CONSTRAINT workouts_pkey PRIMARY KEY (id),
  CONSTRAINT workouts_date_key UNIQUE (date),
  CONSTRAINT workouts_principle_id_fkey FOREIGN KEY (principle_id) REFERENCES principles(id),
  CONSTRAINT workouts_registered_by_fkey FOREIGN KEY (registered_by) REFERENCES profiles(id),
  CONSTRAINT workouts_technique_name_not_empty CHECK (length(TRIM(BOTH FROM technique_name)) > 0),
  CONSTRAINT workouts_technique_what_not_empty CHECK (length(TRIM(BOTH FROM technique_what)) > 0),
  CONSTRAINT workouts_technique_how_not_empty CHECK (length(TRIM(BOTH FROM technique_how)) > 0),
  CONSTRAINT workouts_technique_why_not_empty CHECK (length(TRIM(BOTH FROM technique_why)) > 0)
);

-- Registros de presenca (check-in)
CREATE TABLE public.attendance (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  profile_id uuid NOT NULL,
  workout_id uuid NOT NULL,
  checked_in_at timestamp with time zone NOT NULL DEFAULT now(),
  hygiene_confirmed boolean NOT NULL DEFAULT false,
  created_at timestamp with time zone NOT NULL DEFAULT now(),

  CONSTRAINT attendance_pkey PRIMARY KEY (id),
  CONSTRAINT attendance_unique_per_workout UNIQUE (profile_id, workout_id),
  CONSTRAINT attendance_profile_id_fkey FOREIGN KEY (profile_id) REFERENCES profiles(id) ON DELETE CASCADE,
  CONSTRAINT attendance_workout_id_fkey FOREIGN KEY (workout_id) REFERENCES workouts(id) ON DELETE CASCADE
);

-- Graduacoes (historico de faixas)
CREATE TABLE public.graduations (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  profile_id uuid NOT NULL,
  previous_belt text NOT NULL,
  new_belt text NOT NULL,
  promoted_by uuid NOT NULL,
  promotion_date date NOT NULL DEFAULT CURRENT_DATE,
  notes text,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),

  CONSTRAINT graduations_pkey PRIMARY KEY (id),
  CONSTRAINT graduations_profile_id_fkey FOREIGN KEY (profile_id) REFERENCES profiles(id) ON DELETE CASCADE,
  CONSTRAINT graduations_promoted_by_fkey FOREIGN KEY (promoted_by) REFERENCES profiles(id)
